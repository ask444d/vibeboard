const dicts: Record<Locale, Dict> = { en, ru }
export type I18nKey = keyof typeof en

const TOTAL_KEYS = Object.keys(en).length

export function t(locale:Locale, key: I18nKey | string): string {
  const hit = dicts[locale][key] ?? dicts.en[key]
  if (hit !== undefined) return hit
  if (typeof import.meta !== 'undefined' && (import.meta as unknown as { env?: { DEV?: boolean } }).env?.DEV) {
    console.warn(`[i18n] missing key: ${key}`)
  }
  return key
}

export function getLocaleFromStorage(): Locale {
  try {
    const s = localStorage.getItem('vibeboard-locale') as Locale | null
    if(s && (s==='en' || s==='ru')) return s
  } catch { /* blocked — fallback ниже */ }
  try {
    const nav = typeof navigator !== 'undefined' ? navigator.language : ''
    if(nav && nav.toLowerCase().startsWith('ru')) return 'ru'
  } catch { /* ignore */ }
  return 'en'
}

export function getCoverage(locale: Locale): number {
  const have = Object.keys(dicts[locale] ?? {}).filter(k=> dicts[locale][k] && dicts[locale][k].trim().length>0).length
  return Math.round(have / TOTAL_KEYS * 100)
}
export function getTotalKeys(): number { return TOTAL_KEYS }
export function getTranslatedCount(locale: Locale): number { return Object.keys(dicts[locale] ?? {}).filter(k=> dicts[locale][k]?.trim()).length }
