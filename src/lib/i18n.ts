const dicts: Record<string, Dict> = { en, ru, de, fr, es, zh }
export type I18nKey = keyof typeof en

const TOTAL_KEYS = Object.keys(en).length

function lookupDict(locale: string): Dict | undefined {
  return dicts[locale] ?? customLocales[locale]?.dict
}

export function t(locale:string, key: I18nKey | string): string {
  const hit = lookupDict(locale)?.[key] ?? dicts.en[key]
  if (hit !== undefined) return hit
  if (typeof import.meta !== 'undefined' && (import.meta as unknown as { env?: { DEV?: boolean } }).env?.DEV) {
    console.warn(`[i18n] missing key: ${key}`)
  }
  return key
}

const NAV_PREFIXES: [string, string][] = [['ru','ru'],['de','de'],['fr','fr'],['es','es'],['zh','zh']]

export function getLocaleFromStorage(): Locale {
  try {
    const s = (localStorage.getItem('vibeboard-locale') ?? '').trim().toLowerCase()
    if(s && /^[a-z-]{2,12}$/.test(s)) return s
  } catch { /* blocked — fallback ниже */ }
  try {
    const nav = typeof navigator !== 'undefined' ? navigator.language : ''
    const low = (nav ?? '').toLowerCase()
    for(const [prefix, code] of NAV_PREFIXES) if(low.startsWith(prefix)) return code
  } catch { /* ignore */ }
  return 'en'
}

export function getCoverage(locale: string): number {
  const d = lookupDict(locale) ?? {}
  const have = Object.keys(d).filter(k=> d[k] && d[k].trim().length>0).length
  return Math.round(have / TOTAL_KEYS * 100)
}
export function getTotalKeys(): number { return TOTAL_KEYS }
export function getTranslatedCount(locale: string): number {
  const d = lookupDict(locale) ?? {}
  return Object.keys(d).filter(k=> d[k]?.trim()).length
}
