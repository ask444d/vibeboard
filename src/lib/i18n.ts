type Dict = Record<string, string>

export interface CustomLocaleInfo { code: string; label: string; flag: string; dict: Dict }

const customLocales: Record<string, CustomLocaleInfo> = {}

/** Полная замена пользовательских локалей (вызывается из стора и при старте). */
export function setCustomLocales(list: CustomLocaleInfo[]){
  for(const k of Object.keys(customLocales)) delete customLocales[k]
  for(const l of list){
    if(!l || typeof l.code !== 'string' || !l.code) continue
    customLocales[l.code] = {
      code: l.code,
      label: typeof l.label === 'string' && l.label ? l.label : l.code.toUpperCase(),
      flag: typeof l.flag === 'string' && l.flag ? l.flag : '🌐',
      dict: l.dict && typeof l.dict === 'object' ? l.dict : {},
    }
  }
}

/** Все локали: встроенные + загруженные пользователем. */
export function getAllLocales(): {code:string, label:string, flag:string, custom:boolean}[] {
  return [
    ...locales.map(l => ({ ...l, custom:false })),
    ...Object.values(customLocales).map(c => ({ code:c.code, label:c.label, flag:c.flag, custom:true })),
  ]
}

export type LocaleFileError = 'bad-file' | 'bad-code' | 'code-taken' | 'too-few'
const BUILTIN_CODES = ['en','ru','de','fr','es','zh']
const LOCALE_CODE_RE = /^[a-z]{2,8}(-[a-z]{2,4})?$/

/** Проверка загруженного JSON-перевода. Лишние ключи отбрасываются, пустые — тоже. */
export function parseLocaleFile(data: unknown): { ok: true; value: CustomLocaleInfo } | { ok: false; error: LocaleFileError } {
  if(!data || typeof data !== 'object' || Array.isArray(data)) return { ok:false, error:'bad-file' }
  const o = data as Record<string, unknown>
  const code = typeof o.code === 'string' ? o.code.trim().toLowerCase() : ''
  if(!LOCALE_CODE_RE.test(code)) return { ok:false, error:'bad-code' }
  if(BUILTIN_CODES.includes(code)) return { ok:false, error:'code-taken' }
  const label = typeof o.label === 'string' && o.label.trim() ? o.label.trim().slice(0,40) : code.toUpperCase()
  const flag = typeof o.flag === 'string' && o.flag.trim() ? o.flag.trim().slice(0,8) : '🌐'
  if(!o.dict || typeof o.dict !== 'object' || Array.isArray(o.dict)) return { ok:false, error:'bad-file' }
  const dict: Dict = {}
  for(const [k,v] of Object.entries(o.dict as Record<string, unknown>)){
    if(k in en && typeof v === 'string' && v.trim()) dict[k] = v.trim().slice(0,500)
  }
  if(Object.keys(dict).length < 10) return { ok:false, error:'too-few' }
  return { ok:true, value:{ code, label, flag, dict } }
}

/** Шаблон для перевода: все английские ключи одним файлом. */
export function localeTemplate(): string {
  return JSON.stringify({ code:'', label:'', flag:'🌐', dict: en }, null, 2)
}

